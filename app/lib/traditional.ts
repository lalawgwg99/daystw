function buildCharMap(): Record<string, string> {
  const map: Record<string, string> = {};
  for (let i = 0; i < CHAR_MAP.length; i += 2) {
    map[CHAR_MAP[i]] = CHAR_MAP[i + 1];
  }
  return map;
}

