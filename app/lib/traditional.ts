export function toTaiwanTraditional(text: string): string {
  if (!text) return text;

  let result = text;
  for (const [from, to] of PHRASE_MAP) {
    result = result.split(from).join(to);
  }

  let converted = "";
  for (const char of result) {
    converted += charMap[char] ?? char;
  }

  return converted.replace(/周/g, "週");
}

export function formatLunarDate(text: string, hideYear = false): string {
  let formatted = toTaiwanTraditional(text);
  if (hideYear) {
    formatted = formatted.replace(/二〇\d+年/, "");
  }
  return formatted.trim();
}
